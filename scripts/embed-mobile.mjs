// Embeds mobile/* into firmware/web_assets.h so the ESP32 can serve the phone
// UI straight out of flash with no filesystem upload step.
//
//   npm run mobile:embed          regenerate the header
//   npm run mobile:embed -- --check   fail if the header is stale (CI)

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const OUTPUT = join(root, 'firmware', 'web_assets.h');
const SOURCES = [
  { file: 'index.html', symbol: 'INDEX_HTML', mime: 'text/html; charset=utf-8' },
  { file: 'bridge.js', symbol: 'BRIDGE_JS', mime: 'text/javascript; charset=utf-8' },
  { file: 'app.js', symbol: 'APP_JS', mime: 'text/javascript; charset=utf-8' },
];

function loadSource({ file }) {
  const body = readFileSync(join(root, 'mobile', file), 'utf8');
  const delimiter = `RL_${file.replace(/[^A-Za-z0-9]/g, '_').toUpperCase()}`;
  if (body.includes('\0')) throw new Error(`${file} contains a NUL byte and cannot be embedded`);
  if (body.includes(`)${delimiter}"`)) {
    throw new Error(`${file} contains the raw-string terminator )${delimiter}" — pick another delimiter`);
  }
  return { file, body, delimiter, bytes: Buffer.byteLength(body, 'utf8') };
}

const assets = SOURCES.map((source) => loadSource(source));

const header = [
  '// AUTO-GENERATED by scripts/embed-mobile.mjs — do not edit by hand.',
  '// Sources: mobile/index.html, mobile/bridge.js, mobile/app.js',
  '// Regenerate: npm run mobile:embed',
  '#ifndef RANGELAB_WEB_ASSETS_H',
  '#define RANGELAB_WEB_ASSETS_H',
  '',
  '#include <Arduino.h>',
  '',
  ...assets.map(
    ({ body, symbol, delimiter, bytes }) => [
      `// ${bytes} bytes`,
      `static const char ${symbol}[] PROGMEM = R"${delimiter}(${body})${delimiter}";`,
      '',
    ].join('\n'),
  ),
  `static constexpr size_t WEB_ASSETS_BYTES = ${assets.reduce((total, asset) => total + asset.bytes, 0)};`,
  '',
  '#endif  // RANGELAB_WEB_ASSETS_H',
  '',
].join('\n');

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUTPUT, 'utf8');
  } catch {
    current = '';
  }
  if (current !== header) {
    console.error('firmware/web_assets.h is out of date. Run: npm run mobile:embed');
    process.exit(1);
  }
  console.log(`firmware/web_assets.h matches mobile/ (${assets.reduce((t, a) => t + a.bytes, 0)} bytes)`);
  process.exit(0);
}

writeFileSync(OUTPUT, header);
const total = assets.reduce((sum, asset) => sum + asset.bytes, 0);
for (const asset of assets) console.log(`${asset.file}: ${asset.bytes} bytes`);
console.log(`firmware/web_assets.h written (${total} bytes of flash)`);
